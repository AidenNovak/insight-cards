/** 把预设展开成渲染器要的参数列表（补上 index / total / 继承顶层配色）。 */
export function expandPreset(name) {
  const preset = PRESETS[name];
  if (!preset) {
    throw new Error(`未知预设 "${name}"。可用：${Object.keys(PRESETS).join(", ")}`);
  }
  const total = preset.cards.length;
  return preset.cards.map((card, i) => ({
    ...card,
    palette: card.palette ?? preset.palette ?? "deep-field",
    index: String(i + 1).padStart(2, "0"),
    total,
  }));
}

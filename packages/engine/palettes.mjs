/** 按 id 取调色板；未知 id 直接报错，不静默回退到第一个。 */
export function paletteById(id) {
  const found = PALETTES.find((p) => p.id === id);
  if (!found) {
    throw new Error(`未知调色板 "${id}"。可用：${PALETTES.map((p) => p.id).join(", ")}`);
  }
  return found;
}

/**
 * 在色阶上按 t（0..1）取色，段内线性插值。
 * 主题只需要「这里该多亮」，不需要知道具体是什么颜色——
 * 换调色板时整张图跟着变，这是模板能复用的前提。
 */
export function ramp(stops, t) {
  const x = Math.max(0, Math.min(1, t)) * (stops.length - 1);
  const i = Math.min(stops.length - 2, Math.floor(x));
  const f = x - i;
  const a = stops[i];
  const b = stops[i + 1];
  return [
    a[0] + (b[0] - a[0]) * f,
    a[1] + (b[1] - a[1]) * f,
    a[2] + (b[2] - a[2]) * f,
  ];
}
